// Writes dist/asset-version.ts with a content hash of public/static/**.
// The renderer appends it as ?v=<hash> to static asset URLs, so the value
// only changes when an asset actually changes — no manual bumping.
// Runs after `vite build && unocss` in the dev/build/deploy scripts, so
// the hash covers the freshly generated uno.css too.

import { createHash } from 'node:crypto'
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const walk = (dir) =>
  readdirSync(dir, { withFileTypes: true })
    .flatMap((e) => (e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)]))
    .sort()

const hash = createHash('sha256')
for (const file of walk('public/static')) {
  hash.update(file)
  hash.update(readFileSync(file))
}
const version = hash.digest('hex').slice(0, 12)

mkdirSync('dist', { recursive: true })
writeFileSync(
  'dist/asset-version.ts',
  `// Code generated by scripts/stamp-asset-version.mjs. DO NOT EDIT.\nexport const assetVersion = '${version}'\n`,
)
console.log(`Generated: dist/asset-version.ts (${version})`)
