import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const talksDir = 'talks'
const slugs = readdirSync(talksDir).filter((slug) => statSync(join(talksDir, slug)).isDirectory())

function summarize(text, max = 120) {
  const line = text.replace(/\s+/g, ' ').trim()
  return line.length > max ? `${line.slice(0, max - 1)}…` : line
}

function patchViewer(original, slug) {
  const root = `/slides/${slug}/`
  let html = original.replace(/<!-- ogp:start -->[\s\S]*?<!-- ogp:end -->/, '<title>Peitho Deck</title>')
  html = html.replace(/\s*<base[^>]*>/, '')
  html = html.replace('<head>', `<head>\n  <base href="${root}">`)
  if (!html.includes('const pathSlide =')) {
    const pathRead = 'const pathSlide = location.pathname.match(/\\/(\\d+)\\/?$/);\n      if (pathSlide) return Number(pathSlide[1]);'
    html = html.replace('function readSlideIndexFromUrl() {', `function readSlideIndexFromUrl() {\n      ${pathRead}`)
    html = html.replace('function slideFromUrl(url) {', 'function slideFromUrl(url) {\n    const pathSlide = url.pathname.match(/\\/(\\d+)\\/?$/);\n    if (pathSlide) return Number(pathSlide[1]);')
  }
  html = html.replace("params.set('slide', String(oneBased));", "params.delete('slide');")
  html = html.replace("location.pathname + '?' + params.toString() + location.hash", `${JSON.stringify(root)} + oneBased + (params.size ? '?' + params.toString() : '') + location.hash`)
  html = html.replace('next.searchParams.set("slide", String(normalized.index + 1));', `next.pathname = ${JSON.stringify(root)} + (normalized.index + 1);\n    next.searchParams.delete("slide");`)
  html = html.replace('after load, query is canonical.', 'after load, the numbered path is canonical.')
  const writesPath = html.includes(`${JSON.stringify(root)} + oneBased`)
    || html.includes(`next.pathname = ${JSON.stringify(root)} + (normalized.index + 1)`)
  if (!html.includes('const pathSlide =') || !writesPath || !html.includes(`<base href="${root}">`)) {
    throw new Error(`${slug}: unsupported Peitho viewer URL handling`)
  }
  return html
}

function deckVersion(directory) {
  const hash = createHash('sha256')
  function visit(relative = '') {
    for (const entry of readdirSync(join(directory, relative), { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      const path = join(relative, entry.name)
      if (entry.isDirectory()) visit(path)
      else {
        hash.update(path)
        hash.update('\0')
        hash.update(readFileSync(join(directory, path)))
        hash.update('\0')
      }
    }
  }
  visit()
  return hash.digest('hex').slice(0, 20)
}

const decks = slugs.map((slug) => {
  const directory = join('public', 'slides', slug)
  const manifestPath = join(directory, 'manifest.json')
  if (!existsSync(manifestPath)) return null
  const talkPath = join(talksDir, slug, 'talk.json')
  if (!existsSync(talkPath)) throw new Error(`${talkPath} is required for this published deck`)
  const { date } = JSON.parse(readFileSync(talkPath, 'utf8'))
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date ?? '')) throw new Error(`${talkPath}: date must be YYYY-MM-DD`)
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))
  if (!manifest.slides?.length) throw new Error(`${manifestPath}: at least one slide is required`)

  const indexPath = join(directory, 'index.html')
  const original = readFileSync(indexPath, 'utf8')
  const html = patchViewer(original, slug)
  if (html !== original) writeFileSync(indexPath, html)

  const version = deckVersion(directory)
  return {
    slug, date, title: manifest.title,
    width: manifest.canvasWidth, height: manifest.canvasHeight,
    slides: manifest.slides.map((slide, index) => {
      const title = summarize(slide.text?.title || manifest.title)
      return {
        number: index + 1, key: slide.key, src: slide.src, title,
        description: summarize([slide.text?.body, slide.text?.code].filter(Boolean).join(' ')) || title,
        version: `${version}-${index + 1}`,
      }
    }),
  }
}).filter((deck) => deck !== null).sort((a, b) => b.date.localeCompare(a.date))

mkdirSync('dist', { recursive: true })
writeFileSync('dist/slides.ts', `// Code generated by scripts/generate-slides.mjs. DO NOT EDIT.\nimport type { SlideDeck } from '../slides/types'\nexport const SLIDES: readonly SlideDeck[] = ${JSON.stringify(decks, null, 2)}\n`)
console.log(`Generated: dist/slides.ts (${decks.length} talk(s), ${slugs.length - decks.length} unbuilt)`)
